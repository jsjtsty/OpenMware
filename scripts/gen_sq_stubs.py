"""Generate src/script/generated/sq_binding_names.inc from ref/analysis/sqbind/bindings.json.
Format: SQ_CLASS("ScriptName", "Native::Class", { "method", ... }) ; SQ_STATIC("name") for static (global) functions."""
import json, sys, collections
rows = json.load(open(sys.argv[1], encoding='utf-8'))
classes = collections.OrderedDict()
for r in rows:
    classes.setdefault(r['class'], []).append(r)
out = ["// Generated by scripts/gen_sq_stubs.py - do not edit.\n"]
for cls, rs in classes.items():
    ctor = next((r for r in rs if r['registrar_shape'].get('binding') == 'class_constructor'), None)
    if cls == 'SQMATH':
        for n in sorted({r['script_name'] for r in rs}):
            out.append(f'SQ_GLOBAL("{n}")\n')
        continue
    names = sorted({r['script_name'] for r in rs if r is not ctor})
    cname = ctor['script_name'] if ctor else cls
    body = ", ".join(f'"{n}"' for n in names)
    out.append(f'SQ_CLASS("{cname}", "{cls}", {{{body}}})\n')
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write("".join(out))
print(len(classes), "classes")
